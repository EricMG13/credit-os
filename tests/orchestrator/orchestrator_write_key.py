def refused(left: int, *records: str) -> str:
    return "\n".join((HEADER.format(left=left), *records))


# ------------------------------------------------------------------ the retry reason (D5)
def _f(
    check: str,
    line: int,
    quoted: str,
    reason: str,
    column: int = 1,
    severity: Literal["refusal", "warning"] = "refusal",
) -> Finding:
    return Finding(
        check=check, severity=severity, line=line, column=column, quoted=quoted, reason=reason
    )


