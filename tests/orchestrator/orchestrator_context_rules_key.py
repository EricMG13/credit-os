def on(changes: dict[tuple[Any, ...], Any], base: dict[str, Any] = FULL) -> bytes:
    """`base` with each path set to its value (`DROP` removes the key)."""
    obj = copy.deepcopy(base)
    for path, value in changes.items():
        node: Any = obj
        for step in path[:-1]:
            node = node[step]
        if value is DROP:
            del node[path[-1]]
        else:
            node[path[-1]] = value
    return raw(obj)


