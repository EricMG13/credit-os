def raw(obj: Any) -> bytes:
    """A context dict as the bytes of a file (UTF-8, no BOM)."""
    return json.dumps(obj, ensure_ascii=False).encode("utf-8")


def changed(path: tuple[Any, ...], value: Any, base: dict[str, Any] = MINIMAL) -> bytes:
    """MINIMAL (or `base`) with the value at `path` set; `DROP` removes the key."""
    obj = copy.deepcopy(base)
    node: Any = obj
    for step in path[:-1]:
        node = node[step]
    if value is DROP:
        del node[path[-1]]
    else:
        node[path[-1]] = value
    return raw(obj)


