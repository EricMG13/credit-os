"""Answer key for step 3A, PR 7a-1: the shown and stored form of a source error (C1, D12).
PR 7a-2 adds the launch caps (D13, D16, C3) to this file. Written by the controller before the code
existed, by hand (planner's draft checked line by line; rulings in the run folder's
`7a/rulings.md`); implementers do not edit this file and do not weaken a comparison against it.

SYNTHETIC FIXTURE: every name, size, path, message and note is invented. Digests are repeated
letter pairs, not hashes of anything. Every absolute path starts `/synthetic/` or `C:` + backslash
+ `synthetic`; none is a real folder.

How the values were worked, all by hand:
- A masked note: the known path (the folder) becomes `<home>` and what follows it stays
  (decision 0012 point 2). `note_cut`: `<home>/` is 7 characters, so 493 of the 600 `a` are kept.
  Cutting first would keep 45 + 1 + 454 characters and mask to 461, a different value.
- `long_name`: 8 + 130 + 4 = 142 characters; the shown name is the first 120 (8 + 112) and U+2026.

Shape:
  ERRORS    name -> (folder, class raised, message, notes, pin or None, shown text, stored detail)
"""

Pin = tuple[str, int, str]
Detail = dict[str, str | int | None]

SHA = "ab" * 32  # every pin's digest; not a hash of anything
NOTE_CHARACTERS = 500

BACKSLASH = chr(92)
ELLIPSIS = chr(0x2026)

FOLDER_LEAD = "the source folder or a file in it"

# ------------------------------------------------------------------ C1, D12: a source error
R_CHANGED = "its content differs from the pin taken at launch"
R_TOO_LARGE = "larger than the byte cap"
R_UNREADABLE = "cannot be opened or read, or its content does not match its kind"
R_REFUSED = "refused by a name, path or folder rule"
R_ERROR = "could not be used"

FOLDER = "/synthetic/home/analyst/issuers/acme-holdings"
WINDOWS_FOLDER = (
    "C:" + BACKSLASH + BACKSLASH.join(["synthetic", "home", "analyst", "issuers", "acme-holdings"])
)
_REPORT: Pin = ("filings/annual-report.pdf", 4096, "pdf")
_LEDGER: Pin = ("data/ledger.csv", 2048, "csv")
_NOTES: Pin = ("notes.txt", 120, "text")
_Q3: Pin = ("filings/q3-results.pdf", 4096, "pdf")
_LONG_NAME = "filings/" + "n" * 130 + ".pdf"
_BRACKETS = "Q3 results (final) [v2].pdf"
_REPORT_FILE = f"{FOLDER}/filings/annual-report.pdf"
_CLOSE_NOTE = f"{_REPORT_FILE}: close also failed (Input/output error)"
_CLOSED = "<home>/filings/annual-report.pdf: close also failed (Input/output error)"

_WINDOWS_FILE = WINDOWS_FOLDER + BACKSLASH + "filings" + BACKSLASH + "q3-results.pdf"

Row = tuple[str, str, str, tuple[str, ...], Pin | None, str, Detail]


def _row(
    kept: str,
    reason: str,
    raised: str,
    message: str,
    pin: Pin | None,
    notes: tuple[str, ...] = (),
    note: str | None = None,
    shown: str | None = None,
    folder: str = FOLDER,
) -> Row:
    """`kept` is the class name stored, `raised` the class the test raises. The shown text is
    "<name>: <reason>" unless the row writes it out; the stored source is the pin's whole name."""
    source = None if pin is None else pin[0]
    text = shown or f"{source or FOLDER_LEAD}: {reason}"
    detail: Detail = {"error": kept, "source": source, "reason": reason, "note": note}
    return (folder, raised, message, notes, pin, text, detail)


