Row = tuple[str, str, str, tuple[str, ...], Pin | None, str, Detail]


def _row(
    kept: str,
    reason: str,
    raised: str,
    message: str,
    pin: Pin | None,
    notes: tuple[str, ...] = (),
    note: str | None = None,
    shown: str | None = None,
    folder: str = FOLDER,
) -> Row:
    """`kept` is the class name stored, `raised` the class the test raises. The shown text is
    "<name>: <reason>" unless the row writes it out; the stored source is the pin's whole name."""
    source = None if pin is None else pin[0]
    text = shown or f"{source or FOLDER_LEAD}: {reason}"
    detail: Detail = {"error": kept, "source": source, "reason": reason, "note": note}
    return (folder, raised, message, notes, pin, text, detail)


