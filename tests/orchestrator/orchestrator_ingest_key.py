"""Answer key for step 3A, PR 7a-1: the shown and stored form of a source error (C1, D12).
PR 7a-2 adds the launch caps (D13, D16, C3) to this file. Written by the controller before the code
existed, by hand (planner's draft checked line by line; rulings in the run folder's
`7a/rulings.md`); implementers do not edit this file and do not weaken a comparison against it.

SYNTHETIC FIXTURE: every name, size, path, message and note is invented. Digests are repeated
letter pairs, not hashes of anything. Every absolute path starts `/synthetic/` or `C:` + backslash
+ `synthetic`; none is a real folder.

How the values were worked, all by hand:
- A masked note: the known path (the folder) becomes `<home>` and what follows it stays
  (decision 0012 point 2). `note_cut`: `<home>/` is 7 characters, so 493 of the 600 `a` are kept.
  Cutting first would keep 45 + 1 + 454 characters and mask to 461, a different value.
- `long_name`: 8 + 130 + 4 = 142 characters; the shown name is the first 120 (8 + 112) and U+2026.

Shape:
  ERRORS    name -> (folder, class raised, message, notes, pin or None, shown text, stored detail)
"""

