def _event(n: int, kind: str, **data: Any) -> dict[str, Any]:
    return {"id": f"e{n}", "type": kind, "data": data}


def usage(n: int, **data: Any) -> dict[str, Any]:
    return _event(n, "assistant.usage", **{"model": MODEL, **data})


def message(n: int, content: Any, **data: Any) -> dict[str, Any]:
    return _event(n, "assistant.message", content=content, messageId=f"m{n}", **data)


def start(n: int, call_id: Any, name: Any, **data: Any) -> dict[str, Any]:
    return _event(n, "tool.execution_start", toolCallId=call_id, toolName=name, **data)


def nano(value: Any) -> dict[str, Any]:
    return {"copilotUsage": {"totalNanoAiu": value}}


