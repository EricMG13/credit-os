"""Answer key for step 1C, PR 2b: one call's session events to a Reply. Written by the controller
before the code existed.

Implementers do not edit this file. Every value is invented; no figure comes from a real run.
Key-shaped strings are built from parts so that no scanner reads this file as holding a
credential. An event is {"id", "type", "data"}: the SDK event's envelope id as text, its type
value and its data as wire (camelCase) keys.

Charges are worked by hand: totalNanoAiu is a count of 1E-11 USD, so the charge is that integer
with the decimal point moved eleven places left, written here with all eleven decimals.
    12,300,000 -> 0.00012300000        7,319,425,613 -> 0.07319425613
    7,319,425,613 + 2,680,574,387 = 10,000,000,000 -> 0.10000000000
    2**53 = 9,007,199,254,740,992 -> 90071.99254740992
    5 * 10**29 + 5 * 10**29 = 10**30 -> 10000000000000000000.00000000000 (31 digits, exact)
"""

from typing import Any

MODEL = "gpt-6-sol"
