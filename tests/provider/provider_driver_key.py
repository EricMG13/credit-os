"""Answer key for step 1C, PR 3: one call through the session driver against a fake client.
Written by the controller before the code existed. Implementers do not edit this file. Every
value is invented; key-shaped strings are built from parts. An event is the envelope the binding
hands over: {"id", "type", "data"} and, on a sub-agent's event, "agentId".

The fake clock starts at T0. A script entry is an envelope (handed over at once) or ("tick", s):
no event for s seconds. Charge by hand: 12,300,000 x 1E-11 = 0.00012300000.

A case is (want, given); a field left out of `given` takes its default in DEFAULTS.
  fail    step -> ("ExceptionClassName", "text") it raises, or "timeout": it uses up its whole
          bound on the clock and raises TimeoutError. Steps: open_client, start, list_models,
          open_session, send, next_event, abort, queued, disconnect, stop, force_stop
  takes   step -> seconds it uses on the clock before it returns
  before  "close": close() is called first; "same": the same call was made once before
  want    message is exact (PARSER: the parser's message for the script's events, not compared
          when the case lists `absent`); usage is the five counts in Usage's order; charge is
          format(billed_usd, "f"); turn is (text, tool calls, stop_reason, request_id); finished
          is read when the call's events end, before abort and release; calls are the fake's
          steps for the case's own call (next_event is not one); bounds is step -> the timeout_s
          it was given; system is the text open_session got; absent texts are nowhere in raw or
          message, whatever their case, and raw is then a JSON list as long as the script.
A case that opens a session gives it MODEL, the case's effort, its exchange id as session_id,
and `system`; a sent case sends PROMPT. raw is always written with the parser's separators and,
where no `absent` is listed, is the JSON of exactly the envelopes the call read. No step is
ever given a negative timeout_s. `config_id` is the one the driver was made with.
"""

