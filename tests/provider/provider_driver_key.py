"""Answer key for step 1C, PR 3: one call through the session driver against a fake client.
Written by the controller before the code existed.

Implementers do not edit this file. Every value is invented; no figure comes from a real run.
Key-shaped strings are built from parts so that no scanner reads this file as holding a
credential. An event is the envelope the binding will hand over: {"id", "type", "data"} and,
on a sub-agent's event, "agentId".

The fake clock starts at T0. A script entry is an envelope (handed over at once) or
("tick", s): no event for s seconds. Charge by hand: 12,300,000 x 1E-11 = 0.00012300000.

A case is (want, given); a field left out of `given` takes its default below.
  script      what the session's next_event hands over, in order
  queued      what the session's queued() returns (default [])
  models      what list_models returns
  fail        step name -> ("ExceptionClassName", "text") raised by that step, or "timeout":
              the step uses up its whole bound on the clock and raises TimeoutError.
              Steps: open_client, start, list_models, open_session, send, abort, queued,
              disconnect, stop, force_stop.
  takes       step name -> seconds the step uses on the clock before it returns
  environ, home, idle, overall                the driver's arguments
  messages, tools, effort, exchange_id, call_index      the request
  before      "close": close() is called first; "same": the same call was made once before
  want        kind, error_class      always given
              message               exact text; PARSER means the parser's message for the
                                    script's events (the parser has its own key), compared
                                    exactly unless the case lists `absent`
              usage                 the five counts in Usage's field order, or None
              charge                format(reply.billed_usd, "f"), or None
              turn                  None, or (text, tool calls, stop_reason, request_id)
              started, finished     epoch seconds from the fake clock, or None
              started, finished     (finished is read when the call's events end, before
                                    abort and release)
              calls                 the fake's steps in the order the driver made them, for
                                    the case's own call (not the one `before` made)
              bounds                step -> the timeout_s it was given (only where listed)
              absent                texts that appear nowhere in raw or message, whatever
                                    their case; raw is then also a JSON list as long as script
"""

