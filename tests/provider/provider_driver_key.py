def _want(kind: str, error_class: str | None, message: Any = None, **more: Any) -> dict[str, Any]:
    base = {"usage": None, "charge": None, "turn": None, "started": T0, "finished": T0}
    return {"kind": kind, "error_class": error_class, "message": message, **base, **more}


def _ok(**more: Any) -> dict[str, Any]:
    return _want("ok", None, usage=_FULL, charge=_CHARGE, turn=_TURN, calls=_SENT, **more)


def _figures(error_class: str, message: Any = PARSER, **more: Any) -> dict[str, Any]:
    more = {"usage": _FULL, "charge": _CHARGE, "calls": _ENDED, **more}
    return _want("sent_usage", error_class, message, **more)


def _unknown(error_class: str, message: Any = PARSER, **more: Any) -> dict[str, Any]:
    return _want("sent_unknown", error_class, message, **{"calls": _ENDED, **more})


def _late(error_class: str, seconds: float, **more: Any) -> dict[str, Any]:
    text = _IDLE_OUT if error_class == "IdleTimeout" else _OVERALL_OUT
    return _want("sent_unknown", error_class, text, finished=T0 + seconds, calls=_ABORTED, **more)


def _unsent(error_class: str, message: str, *calls: str) -> dict[str, Any]:
    return _want("not_sent", error_class, message, started=None, finished=None, calls=calls)


def _seen(*cwds: str, **more: Any) -> dict[str, Any]:
    context = [event(5 + n, "session.context_changed", cwd=c, **more) for n, c in enumerate(cwds)]
    return {"script": [*context, *_TURN_SCRIPT]}


