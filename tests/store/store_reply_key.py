def _turn(
    usage: Usage, stop: StopReason = "end", model: str | None = None, request: str | None = None
) -> Turn:
    return Turn(
        text="t",
        tool_calls=(),
        usage=usage,
        stop_reason=stop,
        reported_model=model,
        request_id=request,
    )


def _ok(
    usage: Usage,
    *,
    turn: Turn | None = None,
    message: str | None = None,
    billed: Decimal | None = None,
    raw: bytes | None = None,
    started: float | None = None,
    finished: float | None = None,
    compactions: tuple[Compaction, ...] = (),
) -> Reply:
    return Reply(
        kind="ok",
        turn=turn or _turn(usage),
        error_class=None,
        message=message,
        usage=usage,
        billed_usd=billed,
        raw=raw,
        started_at=started,
        finished_at=finished,
        compactions=compactions,
    )


def _failed(
    kind: ReplyKind,
    error_class: str,
    *,
    usage: Usage | None = None,
    message: str | None = None,
    billed: Decimal | None = None,
    raw: bytes | None = None,
    started: float | None = None,
    finished: float | None = None,
    compactions: tuple[Compaction, ...] = (),
) -> Reply:
    return Reply(
        kind=kind,
        turn=None,
        error_class=error_class,
        message=message,
        usage=usage,
        billed_usd=billed,
        raw=raw,
        started_at=started,
        finished_at=finished,
        compactions=compactions,
    )


def _counts(*values: int | None) -> dict[str, int | None]:
    names = (
        "input_tokens",
        "cached_read_tokens",
        "cache_write_tokens",
        "output_tokens",
        "reasoning_tokens",
    )
    return dict(zip(names, values, strict=True))


