"""Answer key: every kind of `Reply`, boundary values included, and the exact columns the store keeps.

Written by the controller from invented values before the code existed (ruling U14: the second net
can never refuse a real charge). Each `Reply` and `Compaction` here is built with the provider's own
constructors, so importing this file proves each one is valid. Implementers do not edit this file
or weaken a comparison against it.

Used twice:
- 3a-b, on a raw connection migrated to 2: a running run, one open attempt (module "CP-1", attempt
  1) and its open call 0. `UPDATE calls SET closed_at = ?, <CALL columns>` for the call, after
  inserting each COMPACTIONS row with that call key, is accepted, and the rows read back equal.
- 3b, through the store: `close_call` with the case's reply on the same setup writes exactly CALL
  (and `closed_at` from the store's clock) and exactly COMPACTIONS, in this order, positions from 0.

Each case runs on a fresh database. Columns not in CALL are the call's own (key, naming, hold,
opened_at). Texts are stored backslashreplace-escaped (U12); times are the codec's text of the
epoch seconds, NULL for None (U15); money is `format(d, "f")`.
"""

