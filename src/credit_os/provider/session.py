"""The seam between the Copilot driver and the SDK: protocols only. Every call raises on
failure; `TimeoutError` means its bound was hit."""

from typing import Protocol


class SessionLike(Protocol):
    def send(self, prompt: str, *, timeout_s: float) -> None: ...
    def next_event(
        self, *, timeout_s: float
    ) -> object | None: ...  # one envelope; None: none in time
    def queued(self, *, timeout_s: float) -> object: ...  # what is queued now, no waiting
    def abort(self, *, timeout_s: float) -> None: ...
    def disconnect(self, *, timeout_s: float) -> None: ...


class ClientLike(Protocol):
    def start(self, *, timeout_s: float) -> None: ...
    def list_models(self, *, timeout_s: float) -> object: ...
    def open_session(
        self, *, model: str, effort: str, system: str, session_id: str, timeout_s: float
    ) -> SessionLike: ...
    def stop(self, *, timeout_s: float) -> None: ...
    def force_stop(self, *, timeout_s: float) -> None: ...
